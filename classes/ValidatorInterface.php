<?php 
/**
 * Интерфейс для проверки данных рецепта. 
 * 
 * Определяет общий метод, который должны 
 * реализовать все классы валидаторов. 
 */  
interface ValidatorInterface 
{
    /**
     * Проверяет переданные данные и возвращает ошибки. 
     * 
     * @param array $data Данные, полученные из HTML-формы. 
     * @return array Список ошибок валидации. 
     */ 
    public function validate(array $data): array;
} 
